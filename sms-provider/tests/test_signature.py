"""HighLevel's X-GHL-Signature (Ed25519) on the Delivery URL post, checked over the raw bytes, in off, warn and enforce mode.

Every signature here is made with a key pair generated by the test run (conftest.KeyPair). HighLevel's private key is not
ours, so nothing in this file shows a post signed by HighLevel itself would verify.
"""

from __future__ import annotations

import base64
import json
import logging

import pytest
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

from sms_bridge import config as config_mod
from sms_bridge import signature

from .conftest import BRIDGE_TOKEN, OTHER_KEY, TEST_KEY, sms

PUBLISHED_KEY = "MCowBQYDK2VwAyEAi2HR1srL4o18O8BRa7gVJY7G7bupbN3H9AwJrHCDiOg="  # HighLevel's Webhook Integration Guide, 2026-11-10


def body() -> bytes:
    return json.dumps(sms()).encode()


def signed(raw: bytes | None = None, key=TEST_KEY) -> tuple[bytes, dict]:
    raw = body() if raw is None else raw
    return raw, {"X-GHL-Signature": key.sign(raw)}


def post(rig, raw, headers, **kw):
    return rig.post(None, raw=raw, headers=headers, **kw)


def _flipped():
    raw, headers = signed()
    at = raw.index(b"quote")
    return raw[:at] + bytes([raw[at] ^ 1]) + raw[at + 1:], headers  # still valid JSON, one byte different


def _wrong_key():
    return signed(key=OTHER_KEY)


def _missing():
    return body(), {}


def _legacy_only():
    raw, headers = signed()
    return raw, {"X-WH-Signature": headers["X-GHL-Signature"]}  # a good signature under the retired header's name


def _legacy_cannot_rescue():
    raw, headers = signed(key=OTHER_KEY)
    return raw, {"X-GHL-Signature": headers["X-GHL-Signature"], "X-WH-Signature": TEST_KEY.sign(raw)}


def _not_base64():
    return body(), {"X-GHL-Signature": "N/A"}


def _empty():
    return body(), {"X-GHL-Signature": ""}


def _truncated():
    raw, headers = signed()
    return raw, {"X-GHL-Signature": base64.b64encode(base64.b64decode(headers["X-GHL-Signature"])[:32]).decode()}


def _signed_compact_sent_spaced():
    compact = json.dumps(sms(), separators=(",", ":")).encode()
    spaced = json.dumps(sms()).encode()
    assert compact != spaced
    return spaced, {"X-GHL-Signature": TEST_KEY.sign(compact)}  # signed over the re-serialisation, not the bytes received


BAD = {
    "a flipped byte in the body": (_flipped, signature.BAD),
    "a signature from another key": (_wrong_key, signature.BAD),
    "no signature header": (_missing, signature.MISSING),
    "only the legacy header": (_legacy_only, signature.LEGACY_ONLY),
    "a legacy header beside a wrong signature": (_legacy_cannot_rescue, signature.BAD),
    "N/A": (_not_base64, signature.BAD),
    "an empty header": (_empty, signature.MISSING),
    "a truncated signature": (_truncated, signature.BAD),
    "a signature over the re-serialised body": (_signed_compact_sent_spaced, signature.BAD),
}


def _warnings(caplog) -> list[str]:
    """The bridge's signature warnings. A slow stand-in on a busy machine can add an unrelated callback warning."""
    return [r.getMessage() for r in caplog.records if r.name == "sms_bridge" and r.levelno == logging.WARNING and "signature" in r.getMessage()]


# --- the control: a good signature passes in every mode, so a refusal below is for the reason named ---------------

def test_a_correctly_signed_post_is_sent_and_reported(checked_rig):
    raw, headers = signed()
    assert post(checked_rig, raw, headers).status_code == 200
    checked_rig.final()
    assert len(checked_rig.gw.posts) == 1 and checked_rig.hl.calls[0]["body"]["status"] == "delivered"


def test_a_good_signature_logs_no_warning(warn_rig, caplog):
    with caplog.at_level(logging.DEBUG):
        raw, headers = signed()
        assert post(warn_rig, raw, headers).status_code == 200
        warn_rig.final()
    assert not _warnings(caplog)


def test_a_compact_body_signed_as_received_is_accepted(enforce_rig):
    raw = json.dumps(sms(), separators=(",", ":")).encode()
    assert raw != body()
    assert post(enforce_rig, *signed(raw)).status_code == 200  # the bytes are never re-serialised before the check


# --- enforce ----------------------------------------------------------------------------------------------------

@pytest.mark.parametrize("case", list(BAD))
def test_enforce_refuses_with_401_and_sends_nothing(enforce_rig, case):
    raw, headers = BAD[case][0]()
    r = post(enforce_rig, raw, headers)
    assert r.status_code == 401 and r.json() == {"error": "bad or missing signature"}
    assert enforce_rig.gw.posts == [] and enforce_rig.hl.calls == []


def test_enforce_checks_the_signature_before_parsing_the_body(enforce_rig):
    assert post(enforce_rig, b"not json", {}).status_code == 401
    assert post(enforce_rig, b'{"messageId": "m1"}', {}).status_code == 401
    # the control: once the signature is right the body is judged as before
    assert post(enforce_rig, *signed(b"not json")).status_code == 400
    assert post(enforce_rig, *signed(b'{"messageId": "m1"}')).status_code == 400


def test_enforce_still_needs_the_secret(enforce_rig):
    raw, headers = signed()
    assert post(enforce_rig, raw, headers, token="wrong-token-0123456789").status_code == 401
    assert post(enforce_rig, raw, headers, token=None).status_code == 401
    assert enforce_rig.gw.posts == []
    assert post(enforce_rig, raw, headers, token=BRIDGE_TOKEN, header=True).status_code == 200


def test_a_refused_signature_does_not_use_up_the_message_id(enforce_rig):
    raw, headers = _flipped()
    assert post(enforce_rig, raw, headers).status_code == 401
    assert post(enforce_rig, *signed()).status_code == 200
    enforce_rig.final()
    assert len(enforce_rig.gw.posts) == 1


# --- warn -------------------------------------------------------------------------------------------------------

@pytest.mark.parametrize("case", list(BAD))
def test_warn_logs_the_reason_and_still_sends(warn_rig, caplog, case):
    make, reason = BAD[case]
    raw, headers = make()
    with caplog.at_level(logging.DEBUG):
        assert post(warn_rig, raw, headers).status_code == 200
        warn_rig.final()
    assert len(warn_rig.gw.posts) == 1
    warned = _warnings(caplog)
    assert len(warned) == 1 and reason in warned[0]
    for value in list(headers.values()) + [BRIDGE_TOKEN, "Hi Dana"]:
        if value:
            assert value not in warned[0]  # neither a signature, the secret nor the text reaches the log


def test_warn_still_rejects_a_bad_body(warn_rig):
    assert post(warn_rig, *signed(b"not json")).status_code == 400
    assert post(warn_rig, b"not json", {}).status_code == 400


# --- off (the default) ------------------------------------------------------------------------------------------

@pytest.mark.parametrize("case", list(BAD))
def test_off_ignores_the_signature_entirely(rig, caplog, case):
    raw, headers = BAD[case][0]()
    with caplog.at_level(logging.DEBUG):
        assert post(rig, raw, headers).status_code == 200
        rig.final()
    assert len(rig.gw.posts) == 1
    assert not _warnings(caplog)
    assert rig.bridge.ghl_key is None  # nothing is loaded when the check is off


def test_off_with_a_good_signature_is_the_token_only_behaviour(rig):
    assert post(rig, *signed()).status_code == 200


# --- configuration ----------------------------------------------------------------------------------------------

ENV = {"BRIDGE_TOKEN": BRIDGE_TOKEN, "GATEWAY_URL": "http://127.0.0.1:18080", "GATEWAY_USER": "u", "GATEWAY_PASSWORD": "p"}


def test_the_default_mode_is_off_and_the_default_key_is_the_published_one():
    cfg = config_mod.from_env(ENV)
    assert cfg.ghl_signature_mode == "off"
    assert cfg.ghl_public_key_b64 == PUBLISHED_KEY == signature.GHL_ED25519_SPKI_B64
    signature.load_key(cfg.ghl_public_key_b64)  # it parses as an Ed25519 key


@pytest.mark.parametrize("given,want", [("off", "off"), ("warn", "warn"), ("enforce", "enforce"), (" Enforce ", "enforce"), ("", "off")])
def test_the_mode_is_read_from_the_environment(given, want):
    assert config_mod.from_env({**ENV, "GHL_SIGNATURE_MODE": given}).ghl_signature_mode == want


@pytest.mark.parametrize("given", ["on", "true", "enforced", "1", "strict"])
def test_an_unknown_mode_is_refused_not_read_as_off(given):
    with pytest.raises(config_mod.ConfigError, match="GHL_SIGNATURE_MODE"):
        config_mod.from_env({**ENV, "GHL_SIGNATURE_MODE": given})


def test_the_key_override_is_honoured_only_when_bridge_env_is_test():
    env = {**ENV, "GHL_PUBLIC_KEY_B64": TEST_KEY.spki_b64}
    for stray in ({}, {"BRIDGE_ENV": "prod"}, {"BRIDGE_ENV": "TEST"}, {"BRIDGE_ENV": "testing"}):
        assert config_mod.from_env({**env, **stray}).ghl_public_key_b64 == PUBLISHED_KEY
    assert config_mod.from_env({**env, "BRIDGE_ENV": "test"}).ghl_public_key_b64 == TEST_KEY.spki_b64


def test_a_key_that_is_not_an_ed25519_public_key_is_refused_at_start():
    rsa_der = rsa.generate_private_key(public_exponent=65537, key_size=2048).public_key().public_bytes(
        serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    for bad in ("not base64!", base64.b64encode(b"not a key").decode(), base64.b64encode(rsa_der).decode()):
        with pytest.raises(config_mod.ConfigError, match="GHL_PUBLIC_KEY_B64"):
            config_mod.from_env({**ENV, "BRIDGE_ENV": "test", "GHL_PUBLIC_KEY_B64": bad})
